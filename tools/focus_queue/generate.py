#!/usr/bin/env python3
"""ES focus queue generator.

Reads every focus tree in common/national_focus and writes the per-focus parts
of the focus queue mechanic. Run from anywhere:

    python tools/focus_queue/generate.py            # repo root = two folders up
    python tools/focus_queue/generate.py --root D:/Github/East-Showdown

Re-run it after every focus tree change. Focus ids are kept stable in
tools/focus_queue/focus_ids.json so saved queues survive tree edits; never
edit or renumber that file by hand.

Generated (do not edit by hand):
    common/scripted_triggers/es_focus_queue_generated_triggers.txt
    common/scripted_effects/es_focus_queue_generated_effects.txt
    common/scripted_guis/es_focus_queue_tree_generated.txt
    common/scripted_localisation/es_focus_queue_generated_loc.txt
    interface/es_focus_queue_tree_generated.gui
    history/units/es_focus_queue/<id>.txt
    tools/focus_queue/report.txt
"""

import argparse
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import focus_model  # noqa: E402

# ---- layout constants (pixels). Calibrate here if buttons sit off their focus.
FOCUS_STEP_X = 96
FOCUS_STEP_Y = 130
TREE_ORIGIN_X = 199  # +17 from 182: button sits on the top-right corner of the name bar
TREE_ORIGIN_Y = 86   # +21 from 65
TEXT_OFFSET_X = 0
TEXT_OFFSET_Y = 1
TEXT_FONT = "hoi_24header"   # queue number on the tree buttons (was hoi_16mbs)
TEXT_WIDTH = 30
TEXT_HEIGHT = 30
QUEUE_LIMIT = 100
# Tree overlays: a "dirty" scripted GUI is not evaluated until its variable changes after
# the GUI is created, so buttons would show unevaluated until the first daily refresh.
# Without dirty the engine re-evaluates them every tick (only while the focus view is open).
TREE_GUI_DIRTY = False
NAME_BUCKET = 64

HEADER = ("# AUTO-GENERATED by tools/focus_queue/generate.py - do not edit by hand.\n"
          "# Re-run the generator after changing any focus tree.\n")


# ---------------------------------------------------------------------------
def strip_comments(raw):
    out = []
    for line in raw.splitlines():
        res, in_q = [], False
        for ch in line:
            if ch == '"':
                in_q = not in_q
            if ch == "#" and not in_q:
                break
            res.append(ch)
        s = "".join(res).rstrip()
        if s.strip():
            out.append(s)
    return out


def indent_block(raw, depth):
    """Re-indent a raw script block (comments removed) to the given tab depth."""
    lines = strip_comments(raw)
    if not lines:
        return []
    out = []
    level = 0
    for line in lines:
        s = line.strip()
        lead_close = len(s) - len(s.lstrip("}"))
        cur = max(level - lead_close, 0)
        out.append("\t" * (depth + cur) + s)
        level += s.count("{") - s.count("}")
        level = max(level, 0)
    return out


def safe_name(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


# Line endings for generated files. The repo uses "* text=auto", so a Windows
# checkout has CRLF; writing LF there makes every file show as changed in git.
NEWLINE = "\r\n" if os.name == "nt" else "\n"
WRITE_STATS = {"written": 0, "unchanged": 0}


def write(path, text, encoding="utf-8"):
    """Write only when the bytes differ, so unchanged files keep their timestamp
    and don't show up as modified."""
    data = text.replace("\r\n", "\n").replace("\n", NEWLINE).encode(encoding)
    if os.path.isfile(path):
        with open(path, "rb") as f:
            if f.read() == data:
                WRITE_STATS["unchanged"] += 1
                return False
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    with open(path, "wb") as f:
        f.write(data)
    WRITE_STATS["written"] += 1
    return True


class W(object):
    """Tiny line writer."""

    def __init__(self):
        self.lines = []

    def __call__(self, depth, text=""):
        self.lines.append(("\t" * depth + text) if text else "")

    def extend(self, lines):
        self.lines.extend(lines)

    def text(self):
        return "\n".join(self.lines) + "\n"


# ---------------------------------------------------------------------------
class Generator(object):
    def __init__(self, root):
        self.root = root
        self.model = focus_model.Model(os.path.join(root, "common", "national_focus"))
        self.ids_path = os.path.join(HERE, "focus_ids.json")
        self.report = []

    # ---- ids -------------------------------------------------------------
    def load_ids(self):
        if os.path.isfile(self.ids_path):
            with io.open(self.ids_path, "r", encoding="utf-8") as f:
                data = json.load(f)
        else:
            data = {"next_id": 1, "ids": {}}
        self.ids = data["ids"]
        self.next_id = data["next_id"]

    def save_ids(self):
        data = {
            "_comment": "Stable focus-queue ids. Never edit or renumber; saved games store these numbers.",
            "next_id": self.next_id,
            "ids": dict(sorted(self.ids.items(), key=lambda kv: kv[1])),
        }
        write(self.ids_path, json.dumps(data, indent=1, ensure_ascii=False) + "\n")

    # ---- analysis ----------------------------------------------------------
    def analyse(self):
        m = self.model
        self.focus_trees = {}  # focus id -> [tree ids]
        for t in m.trees:
            for fid in t.focus_ids:
                self.focus_trees.setdefault(fid, [])
                if t.id not in self.focus_trees[fid]:
                    self.focus_trees[fid].append(t.id)
        self.excluded = {}
        self.queueable = []
        for t in m.trees:
            for fid in t.focus_ids:
                if fid in self.excluded or fid in self.queueable:
                    continue
                reason = m.focuses[fid].exclusion_reason()
                if reason:
                    self.excluded[fid] = reason
                else:
                    self.queueable.append(fid)
        for fid in self.queueable:
            if fid not in self.ids:
                self.ids[fid] = self.next_id
                self.next_id += 1
        # symmetric mutual exclusion
        self.mutex = {fid: set(f.mutex) for fid, f in m.focuses.items()}
        for fid, f in m.focuses.items():
            for other in f.mutex:
                self.mutex.setdefault(other, set()).add(fid)
        # branch (allow_branch) visibility
        self._branch_memo = {}
        for fid in m.focuses:
            self.needs_branch(fid)
        self.trees = [t for t in m.trees if any(f in self.ids and f in self.queueable for f in t.focus_ids)]

    def needs_branch(self, fid, _stack=None):
        if fid in self._branch_memo:
            return self._branch_memo[fid]
        _stack = _stack or set()
        if fid in _stack or fid not in self.model.focuses:
            return False
        _stack.add(fid)
        f = self.model.focuses[fid]
        res = bool(f.allow_branch_raw)
        for grp in f.prereq_groups:
            if grp and all(self.needs_branch(p, _stack) for p in grp):
                res = True
        _stack.discard(fid)
        self._branch_memo[fid] = res
        return res

    def tree_check(self, w, depth, fid):
        trees = self.focus_trees.get(fid, [])
        if len(trees) == 1:
            w(depth, "has_focus_tree = %s" % trees[0])
        else:
            w(depth, "OR = {")
            for t in trees:
                w(depth + 1, "has_focus_tree = %s" % t)
            w(depth, "}")

    # ---- triggers ------------------------------------------------------------
    def gen_triggers(self):
        w = W()
        w.extend(HEADER.splitlines())
        w(0)
        w(0, "es_fq_supported = {")
        w(1, "OR = {")
        for t in self.trees:
            w(2, "has_focus_tree = %s" % t.id)
        w(1, "}")
        w(0, "}")
        w(0)
        # An explicit allow_branch starts a new visibility gate. Later stages can
        # remain visible after earlier stages have been hidden. Only focuses
        # without their own gate inherit visibility from prerequisite branches.
        for fid in sorted(self._branch_memo):
            if not self._branch_memo[fid]:
                continue
            f = self.model.focuses[fid]
            w(0, "es_fq_branch_%s = {" % fid)
            if f.allow_branch_raw:
                w.extend(indent_block(f.allow_branch_raw, 1))
            else:
                for grp in f.prereq_groups:
                    if grp and all(self._branch_memo.get(p) for p in grp):
                        if len(grp) == 1:
                            w(1, "es_fq_branch_%s = yes" % grp[0])
                        else:
                            w(1, "OR = {")
                            for p in grp:
                                w(2, "es_fq_branch_%s = yes" % p)
                            w(1, "}")
            w(0, "}")
            w(0)
        for fid in self.queueable:
            f = self.model.focuses[fid]
            n = self.ids[fid]
            w(0, "# %s" % fid)
            w(0, "es_fq_can_%d = {" % n)
            self.tree_check(w, 1, fid)
            w(1, "NOT = { has_completed_focus = %s }" % fid)
            if not f.available_if_capitulated:
                w(1, "has_capitulated = no")
            if self._branch_memo.get(fid):
                w(1, "es_fq_branch_%s = yes" % fid)
            for grp in f.prereq_groups:
                if len(grp) == 1:
                    w(1, "has_completed_focus = %s" % grp[0])
                else:
                    w(1, "OR = {")
                    for p in grp:
                        w(2, "has_completed_focus = %s" % p)
                    w(1, "}")
            mx = sorted(self.mutex.get(fid, ()))
            if mx:
                w(1, "NOT = {")
                w(2, "OR = {")
                for p in mx:
                    w(3, "has_completed_focus = %s" % p)
                w(2, "}")
                w(1, "}")
            if f.available_raw:
                w(1, "# available")
                w.extend(indent_block(f.available_raw, 1))
            w(0, "}")
            w(0)
        return w.text()

    # ---- effects -------------------------------------------------------------
    def gen_effects(self):
        w = W()
        w.extend(HEADER.splitlines())
        w(0, "# es_fq_process_<id>: sets temp var es_fq_result = 2 drop, 1 started, 0 blocked.")
        w(0)
        live = set(self.ids[f] for f in self.queueable)
        for fid, n in sorted(self.ids.items(), key=lambda kv: kv[1]):
            w(0, "# %s" % fid)
            w(0, "es_fq_process_%d = {" % n)
            if n not in live:
                w(1, "# focus removed or no longer selectable by the player")
                w(1, "set_temp_variable = { es_fq_result = 2 }")
                w(0, "}")
                w(0)
                continue
            w(1, "if = {")
            w(2, "limit = {")
            w(3, "OR = {")
            w(4, "NOT = {")
            self.tree_check(w, 5, fid)
            w(4, "}")
            w(4, "has_completed_focus = %s" % fid)
            for p in sorted(self.mutex.get(fid, ())):
                w(4, "has_completed_focus = %s" % p)
            w(3, "}")
            w(2, "}")
            w(2, "set_temp_variable = { es_fq_result = 2 }")
            w(1, "}")
            w(1, "else_if = {")
            w(2, "limit = { es_fq_can_%d = yes }" % n)
            w(2, "load_oob = es_focus_queue/%d" % n)
            w(2, "set_temp_variable = { es_fq_result = 1 }")
            w(1, "}")
            w(0, "}")
            w(0)
        return w.text()

    # ---- tree overlay ----------------------------------------------------------
    def gen_tree(self):
        sg = W()
        sg.extend(HEADER.splitlines())
        sg(0, "scripted_gui = {")
        gui = W()
        gui.extend(HEADER.splitlines())
        gui(0, "guiTypes = {")
        self.button_count = 0
        self.variant_report = []
        for t in self.trees:
            wname = "es_fq_tree_%s" % safe_name(t.id)
            elems = []  # (fid, n, j, px, py, act, inact)
            for fid in t.focus_ids:
                if fid not in self.queueable:
                    continue
                n = self.ids[fid]
                variants = self.model.position_variants(fid)
                if len(variants) > 1:
                    self.variant_report.append((t.id, fid, len(variants)))
                for j, (x, y, act, inact) in enumerate(variants):
                    elems.append((fid, n, j, int(round(x * FOCUS_STEP_X)), int(round(y * FOCUS_STEP_Y)), act, inact))
            self.button_count += len(elems)

            # scripted gui
            sg(1, "%s = {" % wname)
            sg(2, "context_type = national_focus_context")
            sg(2, "window_name = %s" % wname)
            sg(2, "parent_window_name = grid_window")
            if TREE_GUI_DIRTY:
                sg(2, "dirty = es_fq_ui_revision")
            sg(2, "ai_enabled = { always = no }")
            sg(2, "visible = {")
            sg(3, "is_ai = no")
            sg(3, "tag = ROOT")
            sg(3, "has_focus_tree = %s" % t.id)
            sg(3, "NOT = { has_country_flag = es_fq_hide_tree }")
            sg(2, "}")
            sg(2, "triggers = {")
            for fid, n, j, px, py, act, inact in elems:
                cond = []
                for a in act:
                    cond.append(("raw", a))
                for b in inact:
                    cond.append(("notraw", b))
                sg(3, "b%d_%d_visible = {" % (n, j))
                self._layout_cond(sg, 4, cond)
                self._shown_cond(sg, 4, fid)
                sg(4, "NOT = {")
                sg(5, "AND = {")
                sg(6, "es_fq_idle = no")
                sg(6, "has_shine_effect_on_focus = %s" % fid)
                sg(5, "}")
                sg(4, "}")
                sg(4, "set_temp_variable = { es_fq_tf_%d = 1 }" % n)
                sg(4, "OR = {")
                sg(5, "NOT = { check_variable = { es_fq_order_%d > 0 } }" % n)
                sg(5, "set_temp_variable = { es_fq_tf_%d = es_fq_frame_%d }" % (n, n))
                sg(4, "}")
                sg(3, "}")
                sg(3, "b%d_%d_click_enabled = {" % (n, j))
                sg(4, "OR = {")
                sg(5, "check_variable = { es_fq_order_%d > 0 }" % n)
                sg(5, "check_variable = { es_fq_queue^num < %d }" % QUEUE_LIMIT)
                sg(4, "}")
                sg(3, "}")
                sg(3, "t%d_%d_visible = {" % (n, j))
                self._layout_cond(sg, 4, cond)
                self._shown_cond(sg, 4, fid)
                sg(4, "check_variable = { es_fq_order_%d > 0 }" % n)
                sg(3, "}")
            sg(2, "}")
            sg(2, "properties = {")
            for fid, n, j, px, py, act, inact in elems:
                sg(3, "b%d_%d = { frame = es_fq_tf_%d }" % (n, j, n))
            sg(2, "}")
            sg(2, "effects = {")
            for fid, n, j, px, py, act, inact in elems:
                sg(3, "b%d_%d_click = {" % (n, j))
                sg(4, "set_temp_variable = { es_fq_toggle_id = %d }" % n)
                sg(4, "es_fq_toggle = yes")
                sg(3, "}")
            sg(2, "}")
            sg(1, "}")

            # gui
            gui(1, "containerWindowType = {")
            gui(2, "name = %s" % wname)
            gui(2, "position = { x = %d y = %d }" % (TREE_ORIGIN_X, TREE_ORIGIN_Y))
            gui(2, "size = { width = 165 height = 128 }")
            gui(2, "clipping = no")
            for fid, n, j, px, py, act, inact in elems:
                gui(2, "buttonType = {")
                gui(3, "name = b%d_%d" % (n, j))
                gui(3, "position = { x = %d y = %d }" % (px, py))
                gui(3, "spriteType = GFX_es_fq_button")
                gui(3, "pdx_tooltip = es_fq_toggle_tt")
                gui(3, "clicksound = click_default")
                gui(2, "}")
                gui(2, "instantTextboxType = {")
                gui(3, "name = t%d_%d" % (n, j))
                gui(3, "position = { x = %d y = %d }" % (px + TEXT_OFFSET_X, py + TEXT_OFFSET_Y))
                gui(3, "text = \"[?es_fq_order_%d|0]\"" % n)
                gui(3, "font = %s" % TEXT_FONT)
                gui(3, "maxWidth = %d" % TEXT_WIDTH)
                gui(3, "maxHeight = %d" % TEXT_HEIGHT)
                gui(3, "format = center")
                gui(3, "alwaystransparent = yes")
                gui(2, "}")
            gui(1, "}")
        sg(0, "}")
        gui(0, "}")
        return sg.text(), gui.text()

    def _layout_cond(self, w, depth, cond):
        for kind, raw in cond:
            if kind == "raw":
                w.extend(indent_block(raw, depth))
            else:
                w(depth, "NOT = {")
                w(depth + 1, "AND = {")
                w.extend(indent_block(raw, depth + 2))
                w(depth + 1, "}")
                w(depth, "}")

    def _shown_cond(self, w, depth, fid):
        w(depth, "NOT = { has_completed_focus = %s }" % fid)
        if self._branch_memo.get(fid):
            w(depth, "es_fq_branch_%s = yes" % fid)

    # ---- scripted localisation -------------------------------------------------
    def gen_loc(self):
        w = W()
        w.extend(HEADER.splitlines())
        entries = sorted(self.ids.items(), key=lambda kv: kv[1])
        live = {}
        for fid, n in entries:
            if fid in self.model.focuses and fid in self.queueable:
                live[n] = fid
        top = max([n for _, n in entries] or [0])
        buckets = range(0, top // NAME_BUCKET + 1)
        for kind in ("name", "icon"):
            w(0, "defined_text = {")
            w(1, "name = es_fq_focus_%s" % kind)
            for b in buckets:
                lo, hi = b * NAME_BUCKET, b * NAME_BUCKET + NAME_BUCKET - 1
                if not any(lo <= n <= hi for n in live):
                    continue
                w(1, "text = {")
                w(2, "trigger = {")
                w(3, "check_variable = { v > %d }" % (lo - 1))
                w(3, "check_variable = { v < %d }" % (hi + 1))
                w(2, "}")
                w(2, "localization_key = \"[es_fq_%s_b%d]\"" % (kind, b))
                w(1, "}")
            w(1, "text = {")
            w(2, "localization_key = %s" % ("es_fq_unknown" if kind == "name" else "GFX_goal_unknown"))
            w(1, "}")
            w(0, "}")
            w(0)
            for b in buckets:
                lo, hi = b * NAME_BUCKET, b * NAME_BUCKET + NAME_BUCKET - 1
                ns = [n for n in sorted(live) if lo <= n <= hi]
                if not ns:
                    continue
                w(0, "defined_text = {")
                w(1, "name = es_fq_%s_b%d" % (kind, b))
                for n in ns:
                    fid = live[n]
                    val = fid if kind == "name" else self.model.focuses[fid].icon
                    w(1, "text = {")
                    w(2, "trigger = { check_variable = { v = %d } }" % n)
                    w(2, "localization_key = \"%s\"" % val)
                    w(1, "}")
                w(1, "text = {")
                w(2, "localization_key = %s" % ("es_fq_unknown" if kind == "name" else "GFX_goal_unknown"))
                w(1, "}")
                w(0, "}")
                w(0)
        return w.text()

    # ---- run ---------------------------------------------------------------------
    def run(self):
        self.load_ids()
        self.analyse()
        r = self.root
        write(os.path.join(r, "common", "scripted_triggers", "es_focus_queue_generated_triggers.txt"), self.gen_triggers())
        write(os.path.join(r, "common", "scripted_effects", "es_focus_queue_generated_effects.txt"), self.gen_effects())
        sg, gui = self.gen_tree()
        write(os.path.join(r, "common", "scripted_guis", "es_focus_queue_tree_generated.txt"), sg)
        write(os.path.join(r, "interface", "es_focus_queue_tree_generated.gui"), gui)
        write(os.path.join(r, "common", "scripted_localisation", "es_focus_queue_generated_loc.txt"), self.gen_loc())
        oob_dir = os.path.join(r, "history", "units", "es_focus_queue")
        if not os.path.isdir(oob_dir):
            os.makedirs(oob_dir)
        live_files = set()
        for fid in self.queueable:
            n = self.ids[fid]
            name = "%d.txt" % n
            live_files.add(name)
            write(os.path.join(oob_dir, name), "focus = {\n\tcurrent = %s\n}\n" % fid)
        removed = 0
        for name in os.listdir(oob_dir):
            if name.endswith(".txt") and name not in live_files:
                os.remove(os.path.join(oob_dir, name))
                removed += 1
        self.save_ids()
        self.write_report(removed)

    def find_unrefreshed_layout_calls(self):
        """Every mark_focus_tree_layout_dirty should be followed by a bump of
        es_fq_ui_revision so the tree buttons appear together with the focuses."""
        missing = []
        scan_dirs = [os.path.join(self.root, "events"), os.path.join(self.root, "common"),
                     os.path.join(self.root, "history")]
        for base in scan_dirs:
            for dirpath, _dirs, files in os.walk(base):
                for name in files:
                    if not name.endswith(".txt") or name.startswith("es_focus_queue"):
                        continue
                    path = os.path.join(dirpath, name)
                    try:
                        lines = focus_model.read_text(path).splitlines()
                    except (IOError, OSError):
                        continue
                    for i, line in enumerate(lines):
                        code = line.split("#", 1)[0]
                        if "mark_focus_tree_layout_dirty" not in code:
                            continue
                        nxt = lines[i + 1] if i + 1 < len(lines) else ""
                        if "es_fq_ui_revision" not in code and "es_fq_ui_revision" not in nxt:
                            missing.append("%s:%d" % (os.path.relpath(path, self.root).replace(os.sep, "/"), i + 1))
        return missing

    def write_report(self, removed_oob):
        m = self.model
        L = ["ES focus queue generator report", "=" * 40, ""]
        L.append("Trees with queue buttons: %d" % len(self.trees))
        for t in self.trees:
            q = sum(1 for f in t.focus_ids if f in self.queueable)
            L.append("  %-32s %4d focuses, %4d queueable" % (t.id, len(t.focus_ids), q))
        L.append("Queueable focuses: %d   tree buttons: %d   stale OOB files removed: %d" % (
            len(self.queueable), self.button_count, removed_oob))
        L.append("")
        L.append("Excluded (cannot be started by the player):")
        for reason in ("auto", "never_available"):
            ids = sorted(f for f, r in self.excluded.items() if r == reason)
            L.append("  %s: %d" % (reason, len(ids)))
            for f in ids:
                L.append("    %s  (%s)" % (f, os.path.basename(m.focuses[f].path)))
        L.append("")
        cond = sorted(f for f in self.queueable if m.focuses[f].has_conditional_never())
        L.append("Kept but REVIEW: available contains a conditional 'always = no' (%d):" % len(cond))
        for f in cond:
            L.append("    %s  (%s)" % (f, os.path.basename(m.focuses[f].path)))
        L.append("")
