import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "common/script_constants/ammo_constants.txt"
CURVES = ROOT / "tools/ammo/ammunition_curves.txt"
CURVE_EFFECTS = ROOT / "common/scripted_effects/ammo_curve_effects.txt"
IDEAS = ROOT / "common/ideas/ammo_ideas.txt"
EFFECTS = ROOT / "common/scripted_effects/ammo_idea_effects.txt"
LOC_RU = ROOT / "localisation/russian/ammo_ideas_l_russian.yml"
LOC_EN = ROOT / "localisation/english/ammo_ideas_l_english.yml"

STEP_PERCENT = 5
ARCHETYPES = ["artillery_equipment", "sp_artillery_chassis", "sp_heavy_artillery_chassis",
              "sp_mlrs_chassis", "sp_tos_chassis", "mortar_equipment"]
STATS = [("soft_attack", "attack"), ("hard_attack", "attack"), ("breakthrough", "breakthrough"), ("defense", "defense")]
CURVE_VARIABLES = [("attack", "ammunition_bonus_attack"), ("breakthrough", "ammunition_bonus_breakthrough"),
                   ("defense", "ammunition_bonus_defense"), ("ai_aggressive", "ammunition_effect_ai_focus_aggressive_factor")]
PICTURE = "GFX_ammunition"
STEP_VARIABLE = "ammunition_supply_step"

GENERATED = "# Generated by tools/ammo/generate_ammunition_effects.py from tools/ammo/ammunition_curves.txt; do not edit"


def read_constants():
    text = CONSTANTS.read_text(encoding="utf-8")
    return {key: float(value) for key, value in re.findall(r"^\s*(\w+)\s*=\s*(-?[\d.]+)\s*$", text, re.MULTILINE)}


def read_curves(level_max_abs):
    text = re.sub(r"#[^\n]*", "", CURVES.read_text(encoding="utf-8"))
    curves = {}
    for name, body in re.findall(r"(\w+)\s*=\s*\{([^}]*)\}", text):
        points = [(float(x), float(y)) for x, y in re.findall(r"(-?[\d.]+)\s*=\s*(-?[\d.]+)", body)]
        xs = [x for x, _ in points]
        if len(points) < 2 or xs[0] != 0 or xs[-1] != level_max_abs or any(a >= b for a, b in zip(xs, xs[1:])):
            sys.exit(f"{CURVES.name}: curve {name} must rise strictly from 0 to level_max_abs = {level_max_abs}")
        curves[name] = points
    missing = {name for name, _ in CURVE_VARIABLES} - curves.keys()
    if missing:
        sys.exit(f"{CURVES.name}: missing curves {', '.join(sorted(missing))}")
    return curves


def curve(points, s):
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if s <= x1:
            return y0 + (y1 - y0) * (s - x0) / (x1 - x0)
    return points[-1][1]


def number(value):
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def idea_name(percent):
    return f"ammunition_{percent}"


def write(path, lines, bom=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8-sig" if bom else "utf-8", newline="")


def ideas_file(curves, steps):
    lines = [GENERATED, "", "ideas = {", "\tcountry = {"]
    for percent in steps:
        s = percent / 100
        lines += [f"\t\t{idea_name(percent)} = {{", "\t\t\tallowed = { always = no }",
                  "\t\t\tallowed_civil_war = { always = yes }", "\t\t\tremoval_cost = -1",
                  f"\t\t\tpicture = {PICTURE}", "", "\t\t\tequipment_bonus = {"]
        for archetype in ARCHETYPES:
            stats = " ".join(f"{stat} = {number(curve(curves[name], s))}" for stat, name in STATS)
            lines.append(f"\t\t\t\t{archetype} = {{ {stats} instant = yes }}")
        lines += ["\t\t\t}", "\t\t}"]
    lines += ["\t}", "}"]
    return lines


def effects_file(steps):
    lines = [GENERATED, "",
             "# Требует ammunition_supply",
             "ammunition_update_idea = {",
             "\tset_temp_variable = {",
             f"\t\tammunition_supply_step_new = {{ value = ammunition_supply multiply = {100 // STEP_PERCENT} "
             f"round = yes multiply = {STEP_PERCENT} }}",
             "\t}",
             "\tif = {",
             "\t\tlimit = {",
             "\t\t\tOR = {",
             f"\t\t\t\tNOT = {{ has_variable = {STEP_VARIABLE} }}",
             f"\t\t\t\tNOT = {{ check_variable = {{ {STEP_VARIABLE} = ammunition_supply_step_new }} }}",
             "\t\t\t}",
             "\t\t}"]
    for percent in steps:
        lines.append(f"\t\tif = {{ limit = {{ has_idea = {idea_name(percent)} }} remove_ideas = {idea_name(percent)} }}")
    lines.append(f"\t\tset_variable = {{ {STEP_VARIABLE} = ammunition_supply_step_new }}")
    for index, percent in enumerate(steps):
        keyword = "if" if index == 0 else "else_if"
        lines.append(f"\t\t{keyword} = {{ limit = {{ check_variable = {{ {STEP_VARIABLE} = {percent} }} }} "
                     f"add_ideas = {idea_name(percent)} }}")
    lines += ["\t}", "}"]
    return lines


# lerp clamps alpha to [0, 1], so each segment adds its full rise past its end and nothing before its start
def curve_effects_file(curves):
    lines = [GENERATED, "", "# Требует ammunition_supply", "ammunition_calculate_effects = {"]
    for name, variable in CURVE_VARIABLES:
        points = curves[name]
        lines += ["\tset_variable = {", f"\t\t{variable} = {{", f"\t\t\tvalue = {number(points[0][1])}"]
        for (x0, y0), (x1, y1) in zip(points, points[1:]):
            alpha = f"{{ value = ammunition_supply subtract = {number(x0)} divide = {number(x1 - x0)} }}"
            lines.append(f"\t\t\tadd = {{ value = 0 lerp = {{ to = {number(y1 - y0)} alpha = {alpha} }} }}")
        lines += ["\t\t}", "\t}"]
    lines.append("}")
    return lines


def loc_file(header, name, desc, steps):
    lines = [header, " " + GENERATED]
    for percent in steps:
        lines.append(f' {idea_name(percent)}: "{name}: {percent} %"')
        lines.append(f' {idea_name(percent)}_desc: "{desc}"')
    return lines


def main():
    constants = read_constants()
    curves = read_curves(constants["level_max_abs"])
    last = round(constants["level_max_abs"] * 100)
    steps = [percent for percent in range(0, last + 1, STEP_PERCENT) if percent != 100]
    write(IDEAS, ideas_file(curves, steps))
    write(CURVE_EFFECTS, curve_effects_file(curves))
    write(EFFECTS, effects_file(steps))
    write(LOC_RU, loc_file("l_russian:", "Обеспеченность боеприпасами",
                           "Бонус действует на артиллерию, САУ, РСЗО, ТОС и миномёты.", steps), bom=True)
    write(LOC_EN, loc_file("l_english:", "Ammunition supply",
                           "The bonus applies to artillery, self-propelled guns, MLRS, TOS and mortars.", steps), bom=True)


if __name__ == "__main__":
    main()
